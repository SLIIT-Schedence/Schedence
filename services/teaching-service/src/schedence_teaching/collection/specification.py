"""Readable collection headers and explicit mappings, separate from source layouts."""

from dataclasses import dataclass


@dataclass(frozen=True)
class Column:
    header: str
    field: str
    format: str
    requirement: str
    explanation: str


def column(header, field, format="text", requirement="required", explanation="Preserve the supplied source value."):
    return Column(header, field, format, requirement, explanation)


