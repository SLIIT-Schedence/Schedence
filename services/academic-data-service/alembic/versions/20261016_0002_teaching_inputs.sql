CREATE TABLE academic.source_datasets (
	id UUID NOT NULL, 
	institution_id UUID NOT NULL, 
	record_key TEXT NOT NULL, 
	filename TEXT NOT NULL, 
	sha256 VARCHAR(64) NOT NULL, 
	provenance_kind VARCHAR(40) NOT NULL, 
	provenance JSONB NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	CONSTRAINT pk_source_datasets PRIMARY KEY (id), 
	CONSTRAINT uq_source_datasets_institution_id_id UNIQUE (institution_id, id), 
	CONSTRAINT uq_source_datasets_institution_id_record_key UNIQUE (institution_id, record_key), 
	CONSTRAINT ck_source_datasets_checksum CHECK (sha256 ~ '^[0-9a-f]{64}$')
);
CREATE TABLE academic.cohort_totals (
	id UUID NOT NULL, 
	institution_id UUID NOT NULL, 
	record_key TEXT NOT NULL, 
	cohort_reference TEXT NOT NULL, 
	academic_year INTEGER NOT NULL, 
	semester INTEGER NOT NULL, 
	stream VARCHAR(10) NOT NULL, 
	student_count INTEGER NOT NULL, 
	source_id UUID NOT NULL, 
	source_values JSONB NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	CONSTRAINT pk_cohort_totals PRIMARY KEY (id), 
	CONSTRAINT fk_source_id_source_datasets FOREIGN KEY(institution_id, source_id) REFERENCES academic.source_datasets (institution_id, id) ON DELETE RESTRICT, 
	CONSTRAINT uq_cohort_totals_institution_id_id UNIQUE (institution_id, id), 
	CONSTRAINT uq_cohort_totals_institution_id_record_key UNIQUE (institution_id, record_key), 
	CONSTRAINT ck_cohort_totals_year CHECK (academic_year BETWEEN 1 AND 4), 
	CONSTRAINT ck_cohort_totals_semester CHECK (semester BETWEEN 1 AND 2), 
	CONSTRAINT ck_cohort_totals_stream CHECK (stream IN ('WEEKDAY','WEEKEND')), 
	CONSTRAINT ck_cohort_totals_count CHECK (student_count > 0), 
	CONSTRAINT uq_cohort_totals_institution_id_source_id_academic_year_d474 UNIQUE (institution_id, source_id, academic_year, semester, stream)
);
